def p(text, style=None):
    return doc.add_paragraph(text, style)

def center(text, size=12, bold=False, before=0, after=6, style=None):
    pp = p(text, style)
    pp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pp.paragraph_format.space_before = Pt(before)
    pp.paragraph_format.space_after = Pt(after)
    rr=pp.runs[0]
    rr.font.size=Pt(size)
    rr.font.bold=bold
    return pp

def page(title):
    doc.add_page_break()
    doc.add_heading(title, level=1)

def h(text):
    doc.add_heading(text, level=2)

def num(v, d=2):
    return f"{v:,.{d}f}".replace(","," ").replace(".",",")

def table(caption, header, rows, widths, numerical=()):
    p(caption, "Caption")
    t=doc.add_table(rows=1,cols=len(header))
    t.alignment=WD_TABLE_ALIGNMENT.CENTER
    t.autofit=False
    for c, w in zip(t.columns, widths):
        c.width=Cm(w)
    props=t._tbl.tblPr
    b=OxmlElement("w:tblBorders")
    for side in ("top","left","bottom","right","insideH","insideV"):
        x=OxmlElement("w:"+side)
        for k,v in (("val","single"),("sz","5"),("color","D9D9D9")):
            x.set(qn("w:"+k),v)
        b.append(x)
    props.append(b)
    margins=OxmlElement("w:tblCellMar")
    for side in ("top","bottom","left","right"):
        e=OxmlElement("w:"+side)
        e.set(qn("w:w"), "76" if side in ("top","bottom") else "102")
        e.set(qn("w:type"), "dxa")
        margins.append(e)
    props.append(margins)
    for i,vals in enumerate([header,*rows]):
        row=t.rows[0] if i==0 else t.add_row()
        pr=row._tr.get_or_add_trPr()
        pr.append(OxmlElement("w:cantSplit"))
        if i==0: pr.append(OxmlElement("w:tblHeader"))
        for j,value in enumerate(vals):
            cell=row.cells[j]
            cell.width=Cm(widths[j])
            cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            cp=cell.paragraphs[0]
            cp.paragraph_format.space_after=Pt(0)
            cp.paragraph_format.line_spacing=1.13
            if j in numerical: cp.alignment=WD_ALIGN_PARAGRAPH.RIGHT
            run=cp.add_run(str(value))
            run.font.size=Pt(10.5)
            run.font.bold=i==0
            if i==0 or i%2==0:
                sh=OxmlElement("w:shd")
                sh.set(qn("w:fill"),"DBE8EE" if i==0 else "F5F8F9")
                cell._tc.get_or_add_tcPr().append(sh)
    doc.add_paragraph().paragraph_format.space_after=Pt(1)

