def num(v, d=2):
    return f"{v:,.{d}f}".replace(",", " ").replace(".", ",")


def ru(iso):
    return date.fromisoformat(iso).strftime("%d.%m.%Y")


def url_text(paragraph, label, url):
    link = OxmlElement("w:hyperlink")
    link.set(qn("r:id"), paragraph.part.relate_to(url, RT.HYPERLINK, is_external=True))
    run, props = OxmlElement("w:r"), OxmlElement("w:rPr")
    for tag, value in (("color", "075F57"), ("u", "single"), ("sz", "21")):
        x = OxmlElement("w:" + tag)
        x.set(qn("w:val"), value)
        props.append(x)
    run.append(props)
    txt = OxmlElement("w:t")
    txt.text = label
    run.append(txt)
    link.append(run)
    paragraph._p.append(link)


def table(caption, header, rows, widths, numerical=()):
    p(caption, "Caption")
    t = doc.add_table(rows=1, cols=len(header))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for c, w in zip(t.columns, widths):
        c.width = Cm(w)
    props = t._tbl.tblPr
    b = OxmlElement("w:tblBorders")
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        x = OxmlElement("w:" + side)
        for k, v in (("val", "single"), ("sz", "5"), ("color", "D9D9D9")):
            x.set(qn("w:" + k), v)
        b.append(x)
    props.append(b)
    margins = OxmlElement("w:tblCellMar")
    for side in ("top", "bottom", "left", "right"):
        e = OxmlElement("w:" + side)
        e.set(qn("w:w"), "76" if side in ("top", "bottom") else "102")
        e.set(qn("w:type"), "dxa")
        margins.append(e)
    props.append(margins)
    for i, vals in enumerate([header, *rows]):
        row = t.rows[0] if i == 0 else t.add_row()
        pr = row._tr.get_or_add_trPr()
        pr.append(OxmlElement("w:cantSplit"))
        if i == 0:
            pr.append(OxmlElement("w:tblHeader"))
        for j, value in enumerate(vals):
            cell = row.cells[j]
            cell.width = Cm(widths[j])
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            cp = cell.paragraphs[0]
            cp.paragraph_format.space_after = Pt(0)
            cp.paragraph_format.line_spacing = 1.13
            if j in numerical:
                cp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            if isinstance(value, tuple):
                url_text(cp, *value)
